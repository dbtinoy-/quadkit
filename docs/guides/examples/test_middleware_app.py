"""Tests for middleware_app.py — runs from docs/guides/examples in CI."""

import pytest

from quadkit.testing import WebTestBed

from middleware_app import create_app


@pytest.mark.asyncio
async def test_middleware_applies_to_every_response():
    async with WebTestBed(create_app()) as bed:
        response = bed.get("/ping")
        response.assert_status(200)
        assert response.json == {"pong": True}
        assert response.headers["x-served-by"] == "quadkit"


@pytest.mark.asyncio
async def test_middleware_also_wraps_framework_endpoints():
    async with WebTestBed(create_app()) as bed:
        # /docs is generated by the web module, not by the controller —
        # the middleware still applies, proving it wraps the whole app.
        response = bed.get("/docs")
        response.assert_status(200)
        assert response.headers["x-served-by"] == "quadkit"
